"""Record every applicant file (one clip per statement paragraph, one for the activity list) with Microsoft neural voices (edge-tts) and write data/tts.js.

    pip install edge-tts
    python tools/make-audio.py            # record missing or changed clips (text or voice changed)
    python tools/make-audio.py --force    # record everything again

Each applicant has their own voice (CAST below): Singapore, Hong Kong, Philippine and British English.
In the cloud workspace set TTS_CA_BUNDLE=/root/.ccr/ca-bundle.crt so edge-tts trusts the proxy.
"""
import asyncio, json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# One real voice per applicant: Singapore, Hong Kong and Philippine English (clear, near-British pronunciation with an
# Asian accent) plus two British voices per gender. The British voices are spread across strong and weak applicants
# so that accent does not line up with quality.  id: (voice, pitch, rate)
CAST = {
    'f01': ('en-PH-RosaNeural',   '+0Hz', '-6%'),   # Mook
    'f02': ('en-HK-SamNeural',    '+0Hz', '-8%'),   # Earth
    'f03': ('en-HK-YanNeural',    '+0Hz', '-8%'),   # Kaew
    'f04': ('en-GB-RyanNeural',   '+0Hz', '-6%'),   # Nont
    'f05': ('en-SG-LunaNeural',   '+0Hz', '-6%'),   # Pim
    'f06': ('en-SG-WayneNeural',  '+0Hz', '-8%'),   # Tee
    'f07': ('en-GB-LibbyNeural',  '+0Hz', '-6%'),   # Nan
    'f08': ('en-PH-JamesNeural',  '+0Hz', '-8%'),   # Oat
    'f09': ('en-GB-ThomasNeural', '+0Hz', '-6%'),   # Golf
    'f10': ('en-GB-SoniaNeural',  '+0Hz', '-6%'),   # Noon
}

if os.environ.get('TTS_CA_BUNDLE'):
    import certifi
    certifi.where = lambda: os.environ['TTS_CA_BUNDLE']
import edge_tts


def fnv(text):
    """Same key as ttsKey() in index.html: FNV-1a 32-bit over UTF-16 code units of the whitespace-normalised text."""
    t = ' '.join(text.split())
    b = t.encode('utf-16-le')
    h = 0x811c9dc5
    for unit in (int.from_bytes(b[i:i + 2], 'little') for i in range(0, len(b), 2)):
        h ^= unit
        h = (h * 0x01000193) & 0xffffffff
    return '%08x' % h


def load_content():
    js = "global.window=global;require(process.argv[1]);process.stdout.write(JSON.stringify(window.SL))"
    out = subprocess.check_output(['node', '-e', js, os.path.join(ROOT, 'data', 'content.js')])
    return json.loads(out)


def manifest_path():
    return os.path.join(ROOT, 'data', 'tts.js')


def old_manifest():
    try:
        s = open(manifest_path(), encoding='utf-8').read()
        return json.loads(s[s.index('{'):s.rindex('}') + 1])
    except Exception:
        return {}


async def record(text, voice, pitch, rate, path):
    for attempt in range(4):
        await edge_tts.Communicate(text, voice, rate=rate, pitch=pitch).save(path)
        if os.path.getsize(path) >= max(8000, 120 * len(text)):
            return
        await asyncio.sleep(1.5)
    raise RuntimeError('clip too small after retries: ' + path)


async def main():
    force = '--force' in sys.argv
    sl = load_content()
    os.makedirs(os.path.join(ROOT, 'audio'), exist_ok=True)
    old = old_manifest()
    prev, prev_cast = old.get('clips', {}), old.get('cast', {})
    clips, cast, jobs = {}, {}, []
    for c in sl['files']:
        voice, pitch, rate = CAST[c['id']]
        cast[c['id']] = '%s %s %s' % (voice, pitch, rate)
        paras = sorted(set(s['para'] for s in c['statement']))
        texts = [('%s-p%d' % (c['id'], n), ' '.join(s['text'] for s in c['statement'] if s['para'] == n)) for n in paras]
        texts.append(('%s-act' % c['id'], c['activities'][0]['text'] + ' ' + c['activities'][1]['text']))
        for key, text in texts:
            h = fnv(text)
            path = os.path.join(ROOT, 'audio', key + '.mp3')
            clips[key] = h
            if force or prev.get(key) != h or prev_cast.get(c['id']) != cast[c['id']] or not os.path.exists(path):
                jobs.append((text, voice, pitch, rate, path))
    if '--prune' in sys.argv:
        for fn in os.listdir(os.path.join(ROOT, 'audio')):
            if fn.endswith('.mp3') and fn[:-4] not in clips:
                os.remove(os.path.join(ROOT, 'audio', fn)); print('pruned', fn)
    sem = asyncio.Semaphore(4)

    async def run(job):
        async with sem:
            await record(*job)
            print('recorded', os.path.basename(job[4]), job[1], job[2], job[3])
    await asyncio.gather(*(run(j) for j in jobs))
    data = {'cast': cast, 'dir': 'audio/', 'clips': clips}
    with open(manifest_path(), 'w', encoding='utf-8') as f:
        f.write('/* Generated by tools/make-audio.py: recorded answer clips (key -> text hash) and each applicant\'s voice. Do not edit by hand. */\n')
        f.write('window.TTS = ' + json.dumps(data, indent=1) + ';\n')
    print(len(jobs), 'clip(s) recorded;', len(clips), 'in manifest')


asyncio.run(main())
